<#
.SYNOPSIS
  Starts the local strangler-fig gateway: nginx on http://localhost:8080 in front of the legacy workspace build
  (IIS Express :55243), the new API (:5212, Development) and the SPA build (served by nginx, internal :5031).

.DESCRIPTION
  Idempotent: a component that already answers is left running (use -Restart to stop everything first).
    1. SPA     npm run build in the FE repo, mode "devgateway": VITE_API_BASE_URL empty (calls /api on the same
               origin) and the dev-token sign-in compiled in (VITE_ENABLE_DEV_TOKEN). Output apps/web/dist.
    2. Legacy  robocopy of the legacy WORKSPACE copy to C:\devgw\legacy (its ConnectionStrings.config comes along, as
               it is), MSBuild 14 Release there, IIS Express /path /port:55243.
    3. API     dotnet build into C:\devgw\api (artifacts path, so the repo's own bin/obj and a second API run from
               them are not touched), then the dll on http://localhost:5212 in Development.
    4. nginx   prefix C:\devgw\nginx (logs, temp, junction spa -> apps/web/dist), config nginx.dev.conf from this folder.
  PIDs and log paths go to C:\devgw\state.json. Nothing secret is printed.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File deploy\dev-gateway\start-dev-gateway.ps1
.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File deploy\dev-gateway\start-dev-gateway.ps1 -Status
.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File deploy\dev-gateway\start-dev-gateway.ps1 -SkipSpaBuild -SkipLegacyBuild
#>
[CmdletBinding()]
param(
    # Only report whether each upstream answers.
    [switch] $Status,
    [switch] $SkipSpaBuild,
    [switch] $SkipLegacyBuild,
    [switch] $SkipApiBuild,
    # Stop everything first (stop-dev-gateway.ps1), then start.
    [switch] $Restart
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'devgw.common.ps1')

function Step([string] $text) { Write-Host "== $text" -ForegroundColor Cyan }

function Show-Status {
    $rows = @(Get-DevGwStatus)
    $rows | Format-Table Component, Up, Http, Pid, Url -AutoSize | Out-String | Write-Host
    return $rows
}

if ($Status) {
    $rows = Show-Status
    if (@($rows | Where-Object { -not $_.Up }).Count) { exit 1 }
    exit 0
}

if ($Restart) { & (Join-Path $PSScriptRoot 'stop-dev-gateway.ps1') }

foreach ($dir in $DevGw.ScratchRoot, $DevGw.LogDir, $DevGw.NginxPrefix, (Join-Path $DevGw.NginxPrefix 'logs'), (Join-Path $DevGw.NginxPrefix 'temp')) {
    if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
}
$state = [ordered]@{ startedUtc = (Get-Date).ToUniversalTime().ToString('u'); logs = $DevGw.LogDir }
$previous = Read-DevGwState
foreach ($k in 'legacyPid', 'apiPid', 'nginxPid') { if ($previous -and $previous.$k) { $state[$k] = $previous.$k } }
function Save-State { $state | ConvertTo-Json | Set-Content -LiteralPath $DevGw.StateFile -Encoding UTF8 }

# Long builds run with output to a log file; the last lines are shown only on failure.
function Invoke-Logged([string] $name, [string] $exe, [string[]] $arguments, [string] $workDir) {
    $log = Join-Path $DevGw.LogDir "$name.log"
    $p = Start-Process -FilePath $exe -ArgumentList $arguments -WorkingDirectory $workDir -NoNewWindow -Wait -PassThru `
        -RedirectStandardOutput $log -RedirectStandardError "$log.err"
    if ($p.ExitCode -ne 0) {
        Get-Content -LiteralPath $log -Tail 30 | Write-Host
        Get-Content -LiteralPath "$log.err" -Tail 30 -ErrorAction SilentlyContinue | Write-Host
        throw "$name failed (exit $($p.ExitCode)); full log: $log"
    }
    Write-Host "  $name ok (log: $log)"
}

# Long-running servers: started through cmd with ShellExecute, so they inherit none of this script's handles. (With
# Start-Process -RedirectStandardOutput they would inherit them, and anyone capturing this script's output, a pipe or
# a CI log, would wait until the servers exit.) cmd writes their output to C:\devgw\logs\<name>.log.
function Start-Detached([string] $name, [string] $exe, [string[]] $arguments, [string] $workDir) {
    $log = Join-Path $DevGw.LogDir "$name.log"
    $quoted = @($exe) + $arguments | ForEach-Object { if ($_ -match '[\s"]') { '"' + $_ + '"' } else { $_ } }
    $command = '/s /c "' + ($quoted -join ' ') + ' > "' + $log + '" 2>&1"'
    Start-Process -FilePath $env:ComSpec -ArgumentList $command -WorkingDirectory $workDir -WindowStyle Hidden
}

# ---------- 1. SPA build ----------
Step 'SPA build (FE repo, mode devgateway)'
$dist = Join-Path $DevGw.FeRepo 'apps\web\dist'
if (-not $SkipSpaBuild) {
    # .env.devgateway.local outranks .env.local, so a developer's local API URL or dev token never reaches this build.
    # Git-ignored (.env.*) and regenerated on every run; it holds no secret.
    $envFile = Join-Path $DevGw.FeRepo 'apps\web\.env.devgateway.local'
    @(
        '# Generated by deploy/dev-gateway/start-dev-gateway.ps1 (API repo). Do not edit; it is rewritten on every run.',
        '# Same-origin API (/api/v1 through the gateway), dev-token sign-in compiled in, no baked-in token.',
        'VITE_API_BASE_URL=',
        'VITE_ENABLE_DEV_TOKEN=true',
        'VITE_DEV_BEARER_TOKEN=',
        'VITE_IDENTITY_AUTHORITY='
    ) | Set-Content -LiteralPath $envFile -Encoding ASCII
    $npm = (Get-Command npm.cmd -ErrorAction Stop).Source
    Invoke-Logged 'spa-build' $npm @('run', 'build', '--workspace', '@cims/web', '--', '--mode', 'devgateway') $DevGw.FeRepo
}
if (-not (Test-Path -LiteralPath (Join-Path $dist 'index.html'))) { throw "No SPA build at $dist (run without -SkipSpaBuild)." }
# Guard: the build must not contain a JWT (a token baked in from an env file would be served to every browser).
$leak = Get-ChildItem -LiteralPath (Join-Path $dist 'assets') -Filter *.js | Select-String -Pattern 'eyJ[A-Za-z0-9_-]{10,}\.eyJ' -List
if ($leak) { throw "The SPA build contains what looks like a JWT ($($leak[0].Filename)). Check the FE env files." }
# The gateway serves its OWN copy of the build. apps/web/dist is rewritten by every ordinary `npm run build`
# (other sessions, CI checks) and such a build lacks the devgateway mode, which once left the sign-in page
# saying "VITE_IDENTITY_AUTHORITY is not set". Only this script writes C:\devgw\spa.
$spaCopy = Join-Path $DevGw.ScratchRoot 'spa'
if (-not $SkipSpaBuild -or -not (Test-Path -LiteralPath (Join-Path $spaCopy 'index.html'))) {
    New-Item -ItemType Directory -Force -Path $spaCopy | Out-Null
    & robocopy $dist $spaCopy /MIR /R:2 /W:2 /NFL /NDL /NJH /NJS /NP | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "Copying the SPA build to $spaCopy failed (robocopy exit $LASTEXITCODE)." }
}
$dist = $spaCopy   # from here on nginx's spa junction points at the gateway's private copy

# ---------- 2. Legacy build ----------
Step 'Legacy build (workspace copy -> C:\devgw\legacy, MSBuild 14 Release)'
$workspaceProject = Join-Path $DevGw.LegacyWorkspace 'CIMS_NextMCC'
if ([IO.Path]::GetFullPath($workspaceProject).StartsWith($DevGw.ForbiddenLegacy, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'Refusing to build the user''s own legacy copy; only the workspace copy may be used.'
}
if (-not $SkipLegacyBuild) {
    if (-not (Test-Path -LiteralPath (Join-Path $workspaceProject 'ConnectionStrings.config'))) {
        throw "The workspace has no ConnectionStrings.config ($workspaceProject); copy ConnectionStrings.config.example there and point it at the Test database."
    }
    New-Item -ItemType Directory -Force -Path $DevGw.LegacySite | Out-Null
    # /E copies new and changed files (ConnectionStrings.config included, unchanged); bin/obj of the workspace are
    # never copied, and the scratch copy's own bin/obj and App_Data logs survive re-runs.
    & robocopy $workspaceProject $DevGw.LegacySite /E /XD bin obj .vs /XF *.user /R:2 /W:2 /NFL /NDL /NJH /NJS /NP | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy failed (exit $LASTEXITCODE)." }
    # The csproj's HintPaths point at ..\packages: a junction to the workspace's NuGet folder.
    $packages = Join-Path (Split-Path $DevGw.LegacySite) 'packages'
    if (-not (Test-Path -LiteralPath $packages)) {
        & cmd /c mklink /J "$packages" "$(Join-Path $DevGw.LegacyWorkspace 'packages')" | Out-Null
    }
    $legacyRunning = Get-DevGwIisProcess
    if ($legacyRunning) { Write-Host '  IIS Express is running on 55243: building anyway (ASP.NET picks up the new bin by itself).' }
    Invoke-Logged 'legacy-build' $DevGw.MSBuild @("`"$(Join-Path $DevGw.LegacySite 'CIMS_NextMCC.csproj')`"", '/p:Configuration=Release', '/m', '/nodeReuse:false', '/v:m', '/nologo') $DevGw.LegacySite
}
[xml] $webConfig = Get-Content -LiteralPath (Join-Path $DevGw.LegacySite 'Web.config') -Raw
$legacyKeyRing = ($webConfig.configuration.appSettings.add | Where-Object { $_.key -eq 'SharedKeyRingPath' }).value
if ($legacyKeyRing -ne $DevGw.KeyRingPath) { throw "Legacy SharedKeyRingPath ($legacyKeyRing) differs from $($DevGw.KeyRingPath)." }

# ---------- 3. API build ----------
Step 'API build (C:\devgw\api)'
$apiPid = Get-ListenerPid $DevGw.ApiPort
if (-not $SkipApiBuild -and -not $apiPid) {
    # Transient file locks (antivirus, a parallel build) are retried once.
    try { Invoke-Logged 'api-build' 'dotnet' @('build', "`"$($DevGw.ApiProject)`"", '-c', 'Debug', '--artifacts-path', $DevGw.ApiArtifacts, '--disable-build-servers', '-nologo', '-v', 'q') $DevGw.RepoRoot }
    catch { Write-Host "  retrying once: $($_.Exception.Message)"; Start-Sleep -Seconds 5; Invoke-Logged 'api-build' 'dotnet' @('build', "`"$($DevGw.ApiProject)`"", '-c', 'Debug', '--artifacts-path', $DevGw.ApiArtifacts, '--disable-build-servers', '-nologo', '-v', 'q') $DevGw.RepoRoot }
}
elseif ($apiPid) { Write-Host "  API already listening on $($DevGw.ApiPort) (pid $apiPid): build skipped" }

# ---------- start the three processes (API first: it may create the first key in the shared ring) ----------
Step 'Start API on :5212 (Development)'
if (-not (Get-ListenerPid $DevGw.ApiPort)) {
    if (-not (Test-Path -LiteralPath $DevGw.ApiDll)) { throw "API not built: $($DevGw.ApiDll)" }
    $env:ASPNETCORE_ENVIRONMENT = 'Development'
    $env:ASPNETCORE_URLS = "http://localhost:$($DevGw.ApiPort)"
    $env:LegacyBridge__SharedKeyRingPath = $DevGw.KeyRingPath
    try { Start-Detached 'api' (Get-Command dotnet).Source @($DevGw.ApiDll) (Split-Path $DevGw.ApiDll) }
    finally { Remove-Item Env:ASPNETCORE_ENVIRONMENT, Env:ASPNETCORE_URLS, Env:LegacyBridge__SharedKeyRingPath -ErrorAction SilentlyContinue }
    [void] (Wait-Url "http://localhost:$($DevGw.ApiPort)/health/live" 120)
}
$state.apiPid = Get-ListenerPid $DevGw.ApiPort; Save-State
Write-Host "  API up (pid $($state.apiPid))"

Step 'Start legacy on :55243 (IIS Express)'
if (-not (Get-DevGwIisProcess) -and -not (Get-ListenerPid $DevGw.LegacyPort)) {
    Start-Detached 'iisexpress' $DevGw.IisExpress @("/path:$($DevGw.LegacySite)", "/port:$($DevGw.LegacyPort)", '/clr:v4.0', '/systray:false') $DevGw.LegacySite
}
# The first request compiles the site (Razor, bundles): allow a few minutes.
[void] (Wait-Url "http://localhost:$($DevGw.LegacyPort)/Account/Login" 300)
$state.legacyPid = (Get-DevGwIisProcess).ProcessId; Save-State
Write-Host "  legacy up (iisexpress pid $($state.legacyPid))"

Step 'Start nginx on :8080 (+ SPA on 127.0.0.1:5031)'
$spaLink = Join-Path $DevGw.NginxPrefix 'spa'
$linkItem = Get-Item -LiteralPath $spaLink -ErrorAction SilentlyContinue
if ($linkItem -and $linkItem.Target -and ([IO.Path]::GetFullPath(@($linkItem.Target)[0]) -ne [IO.Path]::GetFullPath($dist))) {
    & cmd /c rmdir "$spaLink" | Out-Null; $linkItem = $null   # removes the junction only, never the build
}
if (-not $linkItem) { & cmd /c mklink /J "$spaLink" "$dist" | Out-Null }
Copy-NginxConf   # nginx.dev.conf -> C:\devgw\nginx\conf\nginx.conf (re-copied on every start)
$test = Invoke-Nginx @('-t')
if ($test.ExitCode -ne 0) { Write-Host $test.Output; throw 'nginx -t failed.' }
if (Get-DevGwNginxProcesses) {
    $reload = Invoke-Nginx @('-s', 'reload')
    if ($reload.ExitCode -ne 0) { Write-Host $reload.Output; throw 'nginx -s reload failed.' }
    Write-Host '  nginx was running: configuration reloaded'
}
else {
    foreach ($port in $DevGw.GatewayPort, $DevGw.SpaPort) {
        $owner = Get-ListenerPid $port
        if ($owner) { throw "Port $port is already used by pid $owner ($((Get-Process -Id $owner).ProcessName))." }
    }
    $nginx = Start-Process (Find-Nginx) -ArgumentList (Get-NginxBaseArgs) `
        -WorkingDirectory $DevGw.NginxPrefix -PassThru -WindowStyle Hidden
    $state.nginxPid = $nginx.Id; Save-State
    [void] (Wait-Url "$($DevGw.Gateway)/nextmcc-api/health" 30)
}
$state.nginxPid = (Get-Content -LiteralPath (Join-Path $DevGw.NginxPrefix 'logs\nginx.pid') -ErrorAction SilentlyContinue | Select-Object -First 1)
Save-State

Step 'Status'
$rows = Show-Status
Write-Host @"
Gateway      $($DevGw.Gateway)/                (legacy pages; /Account/Login is the SPA sign-in)
Pilot page   $($DevGw.Gateway)/pilot/on  then  $($DevGw.Gateway)/Data/ConfirmArrival   (/pilot/off to go back)
Logs         $($DevGw.LogDir)  and  $($DevGw.NginxPrefix)\logs
Dev token    powershell -NoProfile -ExecutionPolicy Bypass -File deploy\dev-gateway\new-dev-token.ps1 -UserName <PwInfo user>
             (copies the token to the clipboard; paste it under "Use dev token" on the sign-in page)
Verify       powershell -NoProfile -ExecutionPolicy Bypass -File deploy\dev-gateway\verify-dev-gateway.ps1
Stop         powershell -NoProfile -ExecutionPolicy Bypass -File deploy\dev-gateway\stop-dev-gateway.ps1
"@
if (@($rows | Where-Object { -not $_.Up }).Count) { exit 1 }
